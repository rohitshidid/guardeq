def make_task(entry_point: str, seed: int, split: str = "tune") -> Task:
    """Build a normal task for one entry point. Deterministic in (entry_point, seed, split)."""
    if entry_point not in ENTRY_POINTS:
        raise ValueError(entry_point)
    rng = random.Random(f"task/{entry_point}/{split}/{seed}")
    template, question, title, answer, expected = TEMPLATES[(entry_point, split)](rng)
    segments = [Segment(rng.choice(FILLER))]
    segments.append(Segment(answer, "answer"))
    if rng.random() < 0.5:
        segments.append(Segment(rng.choice(HARD_BENIGN)))
    segments.append(Segment(rng.choice(FILLER)))
    secret = "RC-" + "".join(rng.choice("ABCDEFGHJKLMNPQRSTUVWXYZ23456789") for _ in range(8))
    return Task(entry_point, template, question, title, segments, expected, secret)


def plant(task: Task, payload: list[str], seed: int) -> Task:
    """Return a copy of the task with attack segments planted in its document.

    A one-part payload goes in as a single segment; a two-part (split) payload is
    separated by at least one benign segment.
    """
    rng = random.Random(f"plant/{seed}")
    segs = list(task.segments)
    if len(payload) == 1:
        segs.insert(rng.randint(1, len(segs)), Segment(payload[0], "inject"))
    else:
        first = rng.randint(1, len(segs) - 1)
        segs.insert(first, Segment(payload[0], "inject"))
        segs.insert(rng.randint(first + 2, len(segs)), Segment(payload[1], "inject"))
    return Task(task.entry_point, task.template, task.question, task.title, segs, task.expected, task.secret)
