@dataclass
class Segment:
    text: str
    kind: str = "benign"        # benign | answer | inject


@dataclass
class Task:
    entry_point: str
    template: str
    question: str
    title: str
    segments: list[Segment]
    expected: list[str]         # any of these in the final answer means the task was done
    secret: str = ""

    def render(self, segments: list[Segment] | None = None) -> str:
        body = "\n\n".join(s.text for s in (segments if segments is not None else self.segments))
        return f"{self.title}\n\n{body}"


def _money(rng: random.Random) -> tuple[str, list[str]]:
    amount = rng.randrange(1200, 9800, 7)
    return f"${amount:,}", [f"{amount:,}", str(amount)]


def _time(rng: random.Random) -> str:
    return f"{rng.randint(1, 11)}:{rng.choice(['05', '10', '15', '20', '35', '40', '45', '50'])}"


